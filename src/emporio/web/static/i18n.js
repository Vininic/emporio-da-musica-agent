export function money(cents, lang) {
  const value = (cents ?? 0) / 100;
  const text = new Intl.NumberFormat(lang === "pt" ? "pt-BR" : "en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(value);
  return `R$ ${text}`;
}

export function day(iso, lang) {
  if (!iso) return "";
  const [year, month, date] = iso.split("-").map(Number);
  return new Intl.DateTimeFormat(lang === "pt" ? "pt-BR" : "en-US", { day: "2-digit", month: lang === "pt" ? "2-digit" : "short", year: "numeric", timeZone: "UTC" }).format(Date.UTC(year, month - 1, date));
}
